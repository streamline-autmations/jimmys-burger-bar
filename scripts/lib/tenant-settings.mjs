// Builds a restaurant's settings SQL from its infrastructure file
// (supabase/tenants/<slug>.json) and its site config (timezone).

const sqlText = (value) => (value === null || value === undefined ? 'null' : `'${String(value).replace(/'/g, "''")}'`);

/** Minutes the zone is ahead of UTC at `instant`. */
export function zoneOffsetMinutes(instant, timeZone) {
  const parts = new Intl.DateTimeFormat('en-US', {
    timeZone, hour12: false, year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit',
  }).formatToParts(instant);
  const read = (type) => Number(parts.find((part) => part.type === type)?.value ?? '0');
  return (Date.UTC(read('year'), read('month') - 1, read('day'), read('hour') % 24, read('minute')) - Math.floor(instant.getTime() / 60000) * 60000) / 60000;
}

/**
 * pg_cron runs in UTC. Converts a restaurant-local "HH:MM" into a daily cron
 * expression, and reports whether the zone observes daylight saving (pg_cron
 * cannot follow it, so the job would drift an hour for part of the year).
 */
export function dailyCronUtc(localTime, timeZone, year = new Date().getUTCFullYear()) {
  const [hours, minutes] = localTime.split(':').map(Number);
  const offsets = Array.from({ length: 12 }, (_, month) =>
    zoneOffsetMinutes(new Date(Date.UTC(year, month, 15, 12)), timeZone));
  const counts = new Map();
  for (const sample of offsets) counts.set(sample, (counts.get(sample) ?? 0) + 1);
  const offset = [...counts].reduce((mostCommon, candidate) =>
    candidate[1] > mostCommon[1] ? candidate : mostCommon)[0];
  const utc = (((hours * 60 + minutes - offset) % 1440) + 1440) % 1440;
  return {
    expression: `${utc % 60} ${Math.floor(utc / 60)} * * *`,
    observesDst: counts.size > 1,
  };
}

export function validateTenant(infra, config) {
  const problems = [];
  if (infra.slug !== config.slug) problems.push(`supabase/tenants/${infra.slug}.json slug does not match the site config slug "${config.slug}"`);
  if (!/^[a-z]{20}$/.test(infra.supabaseProjectRef ?? '')) {
    problems.push('supabaseProjectRef must be exactly 20 lowercase letters from the Supabase project URL (not a placeholder)');
  }
  try {
    if (typeof config.timezone !== 'string' || !config.timezone.trim()) throw new RangeError();
    new Intl.DateTimeFormat('en-US', { timeZone: config.timezone });
  } catch {
    problems.push(`timezone "${config.timezone ?? ''}" must be a valid IANA time zone`);
  }
  if (!/^[0-9]{1,3}$/.test(infra.phoneCountryCode ?? '')) problems.push('phoneCountryCode must be 1 to 3 digits, e.g. "27"');
  for (const kind of ['order', 'booking', 'review']) {
    const url = infra.webhooks?.[kind];
    if (url === undefined) problems.push(`webhooks.${kind} is missing (use null to switch it off)`);
    else if (url !== null && !/^https:\/\/\S+$/.test(url)) problems.push(`webhooks.${kind} must be an https URL or null`);
    else if (url && /PLACEHOLDER/i.test(url)) problems.push(`webhooks.${kind} is still a placeholder`);
  }
  const localTime = infra.reviewRequests?.localTime;
  if (localTime !== null && !/^([01]\d|2[0-3]):[0-5]\d$/.test(localTime ?? '')) problems.push('reviewRequests.localTime must be "HH:MM" or null');
  if (localTime && !infra.webhooks?.review) problems.push('reviewRequests.localTime is set but webhooks.review is null');
  return problems;
}

export function settingsSql(infra, config) {
  const problems = validateTenant(infra, config);
  if (problems.length) throw new Error(`Tenant "${infra.slug}" is not ready:\n  - ${problems.join('\n  - ')}`);

  const rows = [
    ['timezone', config.timezone, 'IANA zone for restaurant-local rules such as breakfast cut-off'],
    ['phone.country_code', infra.phoneCountryCode, 'Country code used to match local and international forms of one phone number'],
    ['webhook.order', infra.webhooks.order, 'n8n webhook for new order notifications'],
    ['webhook.booking', infra.webhooks.booking, 'n8n webhook for new booking notifications'],
    ['webhook.review', infra.webhooks.review, 'n8n webhook for review request emails'],
  ];
  const set = rows.filter(([, value]) => value !== null);
  const unset = rows.filter(([, value]) => value === null).map(([key]) => key);

  const review = infra.reviewRequests.localTime ? dailyCronUtc(infra.reviewRequests.localTime, config.timezone) : null;
  const cron = review
    ? `${review.observesDst ? `-- WARNING: ${config.timezone} observes daylight saving. pg_cron runs in UTC, so\n-- review emails go out an hour later than ${infra.reviewRequests.localTime} for part of the year.\n` : ''}select cron.schedule('restaurant-direct-review-requests', '${review.expression}', 'select public.send_review_requests()');`
    : '-- Review requests are switched off for this restaurant.';

  return `-- GENERATED by \`npm run tenant:sql -- ${infra.slug}\` from supabase/tenants/${infra.slug}.json
-- and src/tenants/${infra.slug}/config.ts. Do not edit by hand.
--
-- Safe to run more than once. Apply after the baseline migration.

insert into public.app_settings (key, value, description)
values
${set.map(([key, value, description]) => `  (${sqlText(key)}, ${sqlText(value)}, ${sqlText(description)})`).join(',\n')}
on conflict (key) do update set
  value = excluded.value,
  description = excluded.description,
  updated_at = now();
${unset.length ? `
-- Switched off: without a setting the notification is skipped and logged, never an error.
delete from public.app_settings where key in (${unset.map(sqlText).join(', ')});
` : ''}
-- One review job per project, whatever it was named before${review ? ` (${infra.reviewRequests.localTime} ${config.timezone} is ${review.expression} UTC)` : ''}.
select cron.unschedule(jobid) from cron.job where command ~* 'send_review_requests';
${cron}
`;
}
