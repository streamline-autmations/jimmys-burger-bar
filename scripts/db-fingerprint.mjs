// Writes the migrations' structural fingerprint and the query that checks a
// real project against it.
//
//   npm run db:fingerprint
//
// Outputs (both committed):
//   supabase/snapshot/baseline.fingerprint.json   one md5 per table, function, trigger, policy and grant
//   supabase/snapshot/compare.sql                 read-only; paste into a project's SQL editor.
//                                                 Zero rows back means the project matches the migrations.
//
// What this proves, and what it does not: the snapshot is generated from the
// migrations in a local Postgres (with Supabase's default privileges and
// extensions stubbed), so the test suite catches a migration that changes
// structure without the snapshot being regenerated. Whether a LIVE project
// matches is only known by running compare.sql against it. That was done for
// Jimmy's on 2026-09-15 (zero rows, baseline only).
//
// Re-run after changing any migration, and apply the same change to every live
// restaurant project, or compare.sql will report the difference.
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
import { createDatabase, fingerprint } from '../tests/db/harness.mjs';

const literal = (value) => `'${String(value).replace(/'/g, "''")}'`;

export function buildCompareSql(rows) {
  const expected = rows.map((row) => `    (${literal(row.kind)}, ${literal(row.name)}, ${literal(row.fingerprint)})`).join(',\n');
  const probe = fs.readFileSync('supabase/snapshot/fingerprint.sql', 'utf8')
    .replace(/^--.*$/gm, '')
    .replace(/select kind, name, fingerprint from rows\s*order by kind, name;\s*$/m, 'select kind, name, fingerprint from rows')
    .trim();

  return `-- GENERATED by \`npm run db:fingerprint\`. Do not edit by hand.
--
-- Checks a Restaurant Direct project against supabase/migrations. Read-only.
-- Zero rows back means it matches exactly. Any row names the object that is
-- missing, extra, or defined differently.

with actual as (
${probe.replace(/^/gm, '  ')}
),
expected(kind, name, fingerprint) as (
  values
${expected}
)
select coalesce(e.kind, a.kind) as kind,
       coalesce(e.name, a.name) as name,
       case when a.name is null then 'missing from this project'
            when e.name is null then 'not in the migrations'
            else 'defined differently' end as problem
from expected e
full outer join actual a on a.kind = e.kind and a.name = e.name
where a.fingerprint is distinct from e.fingerprint
order by 1, 2;
`;
}

export async function currentFingerprint() {
  return fingerprint(await createDatabase());
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const rows = await currentFingerprint();
  fs.writeFileSync('supabase/snapshot/baseline.fingerprint.json', `${JSON.stringify(rows, null, 2)}\n`);
  fs.writeFileSync('supabase/snapshot/compare.sql', buildCompareSql(rows));
  console.log(`Wrote ${rows.length} fingerprints and supabase/snapshot/compare.sql`);
}
