/** What the installed app shows with no connection, instead of the browser's error page. No guest data. */
export function offlinePage(config: ManifestSource & { venue: { phone?: string } }, demo = process.env.VITE_DEMO === '1'): string {
  const { paper, ink, accent } = config.theme.colors;
  const name = escapeHtml(config.venue.name);
  // The demo's outbound links must stay inert (CLAUDE.md), and this page renders outside DemoShell.
  const phone = config.venue.phone && !demo ?`<p><a href="tel:${escapeHtml(config.venue.phone.replace(/\s/g, ''))}">Call ${name}: ${escapeHtml(config.venue.phone)}</a></p>` : '';
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${name}: offline</title><style>body{margin:0;min-height:100dvh;display:grid;place-items:center;background:${paper};color:${ink};font:17px/1.5 system-ui,sans-serif;text-align:center;padding:24px}
h1{font-size:1.6rem;margin:0 0 8px}a{color:${ink};font-weight:700}button{margin-top:16px;min-height:48px;padding:0 24px;border:0;border-radius:999px;background:${accent};color:${ink};font:700 1rem system-ui,sans-serif}</style></head>
<body><main><h1>You are offline</h1><p>Reconnect to see the menu and order from ${name}.</p>${phone}<button onclick="location.reload()">Try again</button></main></body></html>
`;
}

/**
 * The guest app's worker. It only answers page loads that fail for lack of a
 * connection, with the offline page. Nothing else is cached, so menus, prices
 * and orders always come from the network. Chrome offers its one-tap install
 * only when a worker handles fetches.
 */
export function customerServiceWorker(): string {
  return `// GENERATED by vite-plugin-tenant-html.ts. Caches only the offline page.
const CACHE = 'offline-v1';
const OFFLINE = '/offline.html';
self.addEventListener('install', (event) => event.waitUntil(caches.open(CACHE).then((cache) => cache.add(OFFLINE)).then(() => self.skipWaiting())));
self.addEventListener('activate', (event) => event.waitUntil(caches.keys()
  .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
  .then(() => self.clients.claim())));
self.addEventListener('fetch', (event) => {
  if (event.request.mode !== 'navigate' || event.request.method !== 'GET') return;
  event.respondWith(fetch(event.request).catch(() => caches.match(OFFLINE)));
});
`;
}

export function tenantHtml({ slug, entry }: { slug: string; entry?: string }): Plugin {
  const publicDir = fs.existsSync(`src/tenants/${slug}/public`) ? `src/tenants/${slug}/public` : 'public';
  const tenant = async () => await loadTenant(slug, entry) as never as ManifestSource & { venue: { phone?: string } };
  const files: Record<string, [type: string, body: () => Promise<string>]> = {
    'staff.webmanifest': ['application/manifest+json', async () => staffManifest(await tenant(), publicDir)],
    'staff-sw.js': ['text/javascript', async () => staffServiceWorker(await tenant(), publicDir)],
    'app.webmanifest': ['application/manifest+json', async () => customerManifest(await tenant(), publicDir)],
    'sw.js': ['text/javascript', async () => customerServiceWorker()],
    'offline.html': ['text/html', async () => offlinePage(await tenant())],
  };
  return {
    name: 'restaurant-direct:tenant-html',
    configureServer(server) {
      for (const [fileName, [type, body]] of Object.entries(files)) {
        server.middlewares.use(`/${fileName}`, (_req, res) => {
          void body().then((source) => { res.setHeader('Content-Type', type); res.end(source); });
        });
      }
    },
    async generateBundle() {
      for (const [fileName, [, body]] of Object.entries(files)) {
        this.emitFile({ type: 'asset', fileName, source: await body() });
      }
    },
    async transformIndexHtml(html) {
      const config = await loadTenant(slug, entry) as never as {
        seo: { title: string; description: string; themeColor: string };
        assets: { favicon: string; ogImage: string; siteUrl: string };
        venue: { name: string; nameSuffix: string };
        theme: { colors: Record<string, string>; googleFonts?: string[] };
      };

      const fontHref = config.theme.googleFonts?.length
        ? `https://fonts.googleapis.com/css2?${config.theme.googleFonts
            .map((family) => `family=${family}`)
            .join('&')}&display=swap`
        : null;

      const tokens: Record<string, string> = {
        '%TENANT_TITLE%': escapeHtml(config.seo.title),
        '%TENANT_DESCRIPTION%': escapeHtml(config.seo.description),
        '%TENANT_THEME_COLOR%': config.seo.themeColor,
        '%TENANT_FAVICON%': config.assets.favicon,
        '%TENANT_OG_IMAGE%': config.assets.ogImage,
        '%TENANT_SITE_URL%': config.assets.siteUrl,
        '%TENANT_SITE_NAME%': escapeHtml(`${config.venue.name} ${config.venue.nameSuffix}`.trim()),
        // The boot layer is inline CSS evaluated before any JS, so it cannot
        // read a CSS variable set later by ThemeProvider.
        '%TENANT_PAPER%': config.theme.colors.paper,
        '%TENANT_INK%': config.theme.colors.ink,
        '%TENANT_FONT_LINK%': fontHref
          ? `<link rel="preconnect" href="https://fonts.googleapis.com" />\n    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />\n    <link rel="stylesheet" href="${fontHref}" />`
          : '',
      };

      let output = slug === 'jimmys-staging'
        ? html.replace('</head>', '<meta name="robots" content="noindex,nofollow" /></head>')
        : html;
      for (const [token, value] of Object.entries(tokens)) {
        output = output.split(token).join(value);
      }

      const leftover = output.match(/%TENANT_[A-Z_]+%/g);
      if (leftover) throw new Error(`index.html has unfilled tenant tokens: ${leftover.join(', ')}`);
      return output;
    },
  };
}
